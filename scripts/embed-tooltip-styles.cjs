// Keep CSS editable while shipping it with the content scripts, without a
// page-origin fetch or a second external stylesheet request in the shadow root.
const fs=require('node:fs'),path=require('node:path');
function embedTooltipStyles(){
  const root=path.resolve(__dirname,'..'),styles={};
  for(const name of ['showOriginal','showTranslated'])styles[name]=fs.readFileSync(path.join(root,'src/contentScript/css',name+'.css'),'utf8');
  fs.writeFileSync(path.join(root,'src/lib/tooltipStyles.js'),'// Generated by scripts/embed-tooltip-styles.cjs from contentScript/css.\n"use strict";\nconst twpTooltipStyles = Object.freeze('+JSON.stringify(styles,null,2)+');\n');
}
if(require.main===module)embedTooltipStyles();
module.exports={embedTooltipStyles};
